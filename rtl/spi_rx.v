// =============================================================================
// spi_rx.v — приймач SPI (Rx): послідовний потік MISO -> паралельний байт.
// -----------------------------------------------------------------------------
// Лабораторна робота №3, варіант 12 (SPI, Verilog). Кулинський Я.О., КІ-408.
//
// На кожен імпульс sample (фронт вибірки SCLK, який задає ядро за CPHA)
// приймач зсуває біт MISO у регістр старшим бітом уперед. Після восьмого
// біта байт виводиться на rx_data разом з однотактовим імпульсом rx_valid.
// Сигнал clear на початку транзакції скидає лічильник бітів, тож незавершений
// байт попередньої (перерваної) транзакції не змішується з новим.
// =============================================================================
`timescale 1ns / 1ps
`default_nettype none

module spi_rx (
    input  wire       clk,       // системна частота
    input  wire       rst_n,     // синхронне скидання, активний 0
    input  wire       clear,     // імпульс: початок транзакції, забути частковий байт
    input  wire       sample,    // імпульс: зафіксувати поточний біт MISO
    input  wire       miso,      // MISO після вхідного регістра ядра
    output reg  [7:0] rx_data,   // прийнятий байт
    output reg        rx_valid,  // імпульс 1 такт: rx_data містить новий байт
    output reg  [2:0] bitn       // скільки бітів поточного байта вже прийнято
);

    // 7 старших бітів байта; восьмий (LSB) додається в момент видачі
    reg [6:0] shreg;

    always @(posedge clk) begin
        rx_valid <= 1'b0;                        // за замовчуванням імпульсу немає
        if (!rst_n) begin
            shreg   <= 7'd0;
            bitn    <= 3'd0;
            rx_data <= 8'h00;
        end else if (clear) begin
            bitn <= 3'd0;
        end else if (sample) begin
            if (bitn == 3'd7) begin
                // восьмий біт: байт готовий
                rx_data  <= {shreg, miso};
                rx_valid <= 1'b1;
                bitn     <= 3'd0;
            end else begin
                shreg <= {shreg[5:0], miso};
                bitn  <= bitn + 3'd1;
            end
        end
    end

endmodule

`default_nettype wire
